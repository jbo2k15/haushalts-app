import Badge from '../ui/Badge.jsx'
import { useFairnessConfig } from './useFairnessConfig.js'

const LEVELS = {
  1: { tone: 'neutral', label: 'Leicht' },
  2: { tone: 'info', label: 'Mittel' },
  3: { tone: 'primary', label: 'Aufwändig' },
}

// Aufwand als Badge in der Aufgabenliste der Verwaltung.
export default function DifficultyBadge({ task }) {
  const config = useFairnessConfig()
  if (!config?.enabled || task.type === 'once' || task.isAutoGenerated) return null
  const level = LEVELS[task.difficulty] || LEVELS[2]
  return <span className="shrink-0" data-testid="difficulty-badge"><Badge tone={level.tone}>{level.label}</Badge></span>
}
