import { describe, it, expect, vi, afterEach, beforeEach } from 'vitest'
import bcrypt from 'bcryptjs'
import prisma from '../../src/lib/prisma.js'

vi.mock('../../src/services/push.js', () => ({ sendPushToUser: vi.fn() }))
const { sendPushToUser } = await import('../../src/services/push.js')
const { sendDailyReminders, sendWeeklyReminders, sendMonthlyReminders } = await import('../../src/services/scheduler.js')

afterEach(() => {
  vi.useRealTimers()
  sendPushToUser.mockClear()
})

function mockNow(isoString) {
  vi.useFakeTimers()
  vi.setSystemTime(new Date(isoString))
}

async function createUser(overrides = {}) {
  const passwordHash = await bcrypt.hash('Test1234!x', 4)
  return prisma.user.create({
    data: { email: `${Math.random()}@test.com`, passwordHash, name: 'Test User', role: 'user', approved: true, ...overrides },
  })
}

async function createTask(overrides = {}) {
  return prisma.task.create({ data: { title: 'Aufgabe', type: 'daily', priority: 'normal', isActive: true, ...overrides } })
}

describe('sendDailyReminders', () => {
  beforeEach(() => vi.clearAllMocks())

  it('nennt die Titel, wenn 3 oder weniger Aufgaben offen sind', async () => {
    mockNow('2026-07-20T19:00:00Z') // 21:00 Uhr Berlin (Sommerzeit)
    await createUser()
    await createTask({ title: 'Blumen gießen' })
    await createTask({ title: 'Geschirrspüler ausräumen' })

    await sendDailyReminders()

    expect(sendPushToUser).toHaveBeenCalled()
    const body = sendPushToUser.mock.calls[0][1].body
    expect(body).toBe('Noch offen heute: Blumen gießen, Geschirrspüler ausräumen.')
  })

  it('lässt heute übersprungene Aufgaben in der Erinnerung weg', async () => {
    mockNow('2026-07-20T19:00:00Z')
    await createUser()
    await createTask({ title: 'Blumen gießen' })
    const skipped = await createTask({ title: 'Geschirrspüler ausräumen' })
    await prisma.taskLog.create({ data: { taskId: skipped.id, taskTitle: skipped.title, status: 'skipped', forDate: '2026-07-20' } })

    await sendDailyReminders()

    expect(sendPushToUser.mock.calls[0][1].body).toBe('Noch offen heute: Blumen gießen.')
  })

  it('schickt keine Erinnerung, wenn alle offenen Aufgaben übersprungen wurden', async () => {
    mockNow('2026-07-20T19:00:00Z')
    await createUser()
    const skipped = await createTask({ title: 'Blumen gießen' })
    await prisma.taskLog.create({ data: { taskId: skipped.id, taskTitle: skipped.title, status: 'skipped', forDate: '2026-07-20' } })

    await sendDailyReminders()

    expect(sendPushToUser).not.toHaveBeenCalled()
  })

  it('nennt nur den Zähler, wenn mehr als 3 Aufgaben offen sind', async () => {
    mockNow('2026-07-20T19:00:00Z')
    await createUser()
    for (const title of ['A', 'B', 'C', 'D']) await createTask({ title })

    await sendDailyReminders()

    const body = sendPushToUser.mock.calls[0][1].body
    expect(body).toBe('Du hast noch 4 offene Aufgaben heute.')
  })

  it('schickt keine Benachrichtigung, wenn keine Aufgabe offen ist', async () => {
    mockNow('2026-07-20T19:00:00Z')
    await createUser()

    await sendDailyReminders()

    expect(sendPushToUser).not.toHaveBeenCalled()
  })

  it('zählt eine bereits wetterbedingt automatisch erledigte (system-completed) Aufgabe nicht als offen', async () => {
    // Regression: system-completed hat bewusst keine TaskCompletion (siehe
    // domain/tasks.js) - ohne Fix wuerde die Erinnerung sie trotzdem nennen.
    mockNow('2026-07-20T19:00:00Z')
    await createUser()
    const task = await createTask({ title: 'Blumen gießen', weatherDependent: true })
    await prisma.taskLog.create({ data: { taskId: task.id, taskTitle: task.title, status: 'system-completed', forDate: '2026-07-20' } })

    await sendDailyReminders()

    expect(sendPushToUser).not.toHaveBeenCalled()
  })
})

describe('sendDailyReminders — gleiche Quelle wie die Aufgabenliste', () => {
  beforeEach(() => vi.clearAllMocks())

  // 2026-07-20 ist ein Montag, 21:00 Uhr Berlin.
  const MONDAY_EVENING = '2026-07-20T19:00:00Z'

  it('nennt die Tonne am Abend vor der Abholung, aber nicht mehr am Abholtag und nicht als Vorab-Info', async () => {
    mockNow('2026-07-20T19:00:00Z') // 21:00 Uhr Berlin, 20.07.
    await createUser()
    const waste = { type: 'once', isAutoGenerated: true }
    await createTask({ ...waste, title: 'Gelbe Tonne rausstellen', dueDate: '2026-07-20' }) // Abholung morgen
    await createTask({ ...waste, title: 'Papiertonne rausstellen', dueDate: '2026-07-19' }) // Abholung war heute
    await createTask({ ...waste, title: 'Restmülltonne rausstellen', dueDate: '2026-07-22' }) // nur Vorab-Info

    await sendDailyReminders()

    expect(sendPushToUser.mock.calls[0][1].body).toBe('Noch offen heute: Gelbe Tonne rausstellen.')
  })

  it('nennt eine offene eigene einmalige Aufgabe ab ihrem Fälligkeitstag, eine erledigte Tonne nicht', async () => {
    mockNow('2026-07-20T19:00:00Z')
    const user = await createUser()
    await createTask({ type: 'once', title: 'Keller aufräumen', dueDate: '2026-07-18' })
    await createTask({ type: 'once', title: 'Später', dueDate: '2026-07-25' })
    const tonne = await createTask({ type: 'once', isAutoGenerated: true, title: 'Gelbe Tonne rausstellen', dueDate: '2026-07-20' })
    await prisma.taskCompletion.create({ data: { taskId: tonne.id, completedBy: user.id, forDate: '2026-07-20' } })

    await sendDailyReminders()

    expect(sendPushToUser.mock.calls[0][1].body).toBe('Noch offen heute: Keller aufräumen.')
  })

  it('nennt eine überfällige Wochentags-Aufgabe vom Vortag', async () => {
    mockNow(MONDAY_EVENING)
    await createUser()
    await createTask({ title: 'Sonntags-Aufgabe', weekdays: JSON.stringify([0]), createdAt: new Date('2026-07-01T00:00:00Z') })

    await sendDailyReminders()

    expect(sendPushToUser.mock.calls[0][1].body).toContain('Sonntags-Aufgabe')
  })

  it('nennt eine Wochenaufgabe, deren fester Wochentag heute ist', async () => {
    mockNow(MONDAY_EVENING)
    await createUser()
    await createTask({ title: 'Papier wegbringen', type: 'weekly', fixedWeekday: 1 })
    await createTask({ title: 'Fenster putzen', type: 'weekly' }) // ohne festen Tag: nur Wochen-Erinnerung

    await sendDailyReminders()

    expect(sendPushToUser.mock.calls[0][1].body).toBe('Noch offen heute: Papier wegbringen.')
  })

  it('nennt eine Monatsaufgabe, deren fester Tag heute ist', async () => {
    mockNow(MONDAY_EVENING)
    await createUser()
    await createTask({ title: 'Zählerstand ablesen', type: 'monthly', monthlyInterval: 1, nextDueMonth: '2026-07', fixedDayOfMonth: 20 })

    await sendDailyReminders()

    expect(sendPushToUser.mock.calls[0][1].body).toBe('Noch offen heute: Zählerstand ablesen.')
  })
})

