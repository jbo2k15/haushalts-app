// Familien-Display: Zugangsschluessel verwalten und die Daten fuer das
// Wanddisplay in EINER Antwort zusammenstellen. Die Fachlogik (was ist heute
// faellig, wer hat wie viele Punkte, was ist knapp) bleibt in den bestehenden
// Domaenenmodulen - hier wird nur gebuendelt und auf die Felder reduziert, die
// ein Display braucht.
import { randomBytes } from 'crypto'
import prisma from '../lib/prisma.js'
import { httpError } from '../lib/httpError.js'
import { todayString } from '../lib/dates.js'
import { getTaskOverview, getStats } from './tasks.js'
import { listLowStockItems } from './storage.js'
import { getCountMode } from './fairness.js'
import { DISPLAY_TOKEN_PREFIX, hashDisplayToken } from '../middleware/display.js'

export const MAX_DISPLAY_TOKENS = 10

const TOKEN_SELECT = { id: true, name: true, createdAt: true, lastUsedAt: true }

export async function listTokens() {
  return prisma.displayToken.findMany({ orderBy: { createdAt: 'asc' }, select: TOKEN_SELECT })
}

// Legt einen Schluessel an und gibt den Klartext GENAU EINMAL zurueck -
// gespeichert wird nur der Hash, er laesst sich spaeter nicht mehr anzeigen.
export async function createToken({ name } = {}) {
  if (typeof name !== 'string' || name.trim().length === 0) throw httpError(400, 'Name ist erforderlich')
  if (name.trim().length > 60) throw httpError(400, 'Name darf maximal 60 Zeichen haben')
  if (await prisma.displayToken.count() >= MAX_DISPLAY_TOKENS) {
    throw httpError(400, `Maximal ${MAX_DISPLAY_TOKENS} Display-Schlüssel. Bitte erst einen alten löschen.`)
  }
  const token = DISPLAY_TOKEN_PREFIX + randomBytes(32).toString('base64url')
  const created = await prisma.displayToken.create({
    data: { name: name.trim(), tokenHash: hashDisplayToken(token) },
    select: TOKEN_SELECT,
  })
  return { ...created, token }
}

export async function deleteToken(id) {
  const existing = await prisma.displayToken.findUnique({ where: { id } })
  if (!existing) throw httpError(404, 'Schlüssel nicht gefunden')
  await prisma.displayToken.delete({ where: { id } })
  return { message: 'Gelöscht' }
}

function slimTask(t) {
  return {
    id: t.id,
    title: t.title,
    type: t.type,
    priority: t.priority,
    timeOfDay: t.timeOfDay ?? null,
    difficulty: t.difficulty,
    allowMultiple: t.allowMultiple,
    completed: !!t.completed,
    count: t.count ?? (t.completed ? 1 : 0),
    completedBy: t.completedBy ?? null,
    isOverdue: !!t.isOverdue,
    skipped: !!t.skipped,
    systemCompleted: !!t.systemCompleted,
    infoOnly: !!t.infoOnly,
    isAutoGenerated: t.isAutoGenerated,
    dueDate: t.dueDate ?? null,
  }
}

export async function getOverview() {
  const [overview, stats, lowStock, countMode] = await Promise.all([
    getTaskOverview(),
    getStats(),
    listLowStockItems(),
    getCountMode(),
  ])
  return {
    generatedAt: new Date().toISOString(),
    date: todayString(),
    // "count" = Rangliste zaehlt Erledigungen, "weighted" = Punkte nach Aufwand.
    countMode,
    // Alle waehlbaren Personen (Konten und Profile) mit Farbe und Stand.
    people: stats,
    tasks: {
      daily: overview.daily.map(slimTask),
      weekly: overview.weekly.map(slimTask),
      monthly: overview.monthly.map(slimTask),
      once: overview.once.map(slimTask),
    },
    lowStock,
  }
}
