import prisma from '../lib/prisma.js'
import { addDaysToDateString } from '../lib/dates.js'
import { broadcastTasksUpdated } from '../lib/sse.js'
import { fetchIcalWithRetry, toDateString } from './waste-calendar.js'

// Dienstplan-Kalender: holt Dienste aus einem iCal-Abo (z. B. Hühnerstall-
// Dienstplan) und legt sie als einmalige Aufgaben an, die nur an ihrem
// Diensttag erscheinen. Aufbau wie der Abfallkalender-Sync:
//   - DUTY_ICAL_URL    geheimer Kalender-Link (https), ohne ihn bleibt alles aus
//   - DUTY_ICAL_FILTER optional: nur Termine, in denen dieser Text vorkommt
//                      (für ein Abo, das die Dienste aller Familien enthält)
//   - DUTY_ICAL_LABEL  optional: Vorsatz im Aufgabentitel, z. B. "Hühner"
//
// Aufgaben tragen isAutoGenerated = true (nicht bearbeitbar, nicht im Export)
// und autoSource = "duty", damit Abfallkalender-Logik sie nicht anfasst.

const TZ = 'Europe/Berlin'
export const DUTY_SOURCE = 'duty'
// Dienste schon einige Tage im Voraus anlegen, damit ein Ausfall des Abos am
// Diensttag selbst die Aufgabe nicht verschluckt. Angezeigt werden sie erst am
// Diensttag (domain/tasks.js).
const BANK_LEAD_DAYS = 7
const MAX_SUMMARY_LENGTH = 80

function todayBerlin() {
  return new Intl.DateTimeFormat('sv-SE', { timeZone: TZ }).format(new Date())
}

function textOf(value) {
  if (value == null) return ''
  if (typeof value === 'object') return typeof value.val === 'string' ? value.val : ''
  return String(value)
}

function timeOfDayFor(minutes) {
  if (minutes == null) return null
  if (minutes < 11 * 60) return 'morning'
  if (minutes < 15 * 60) return 'noon'
  return 'evening'
}

// Macht aus einem Kalendereintrag eine Dienst-Aufgabe oder null, wenn er nicht
// passt. Exportiert, damit die Zuordnung ohne iCal-Abruf testbar ist.
export function dutyFromEvent(event, { filter = '', label = '' } = {}) {
  if (!event || event.type !== 'VEVENT') return null
  const summary = textOf(event.summary).trim()
  if (!summary) return null

  if (filter) {
    // Ganztext-Suche über die üblichen Felder: je nach Abo steht die Familie
    // im Titel, in der Beschreibung oder bei den Teilnehmern.
    const haystack = [
      summary,
      textOf(event.description),
      textOf(event.location),
      JSON.stringify(event.attendee ?? ''),
      JSON.stringify(event.organizer ?? ''),
    ].join(' ').toLowerCase()
    if (!haystack.includes(filter.toLowerCase())) return null
  }

  const start = new Date(event.start)
  if (Number.isNaN(start.getTime())) return null

  // Ganztägige Termine liefert node-ical als lokale Mitternacht; dort zählt
  // das Kalenderdatum, nicht die Berliner Uhrzeit.
  const dateOnly = event.datetype === 'date' || event.start?.dateOnly === true
  let dueDate
  let time = null
  let minutes = null
  if (dateOnly) {
    dueDate = toDateString(start)
  } else {
    dueDate = new Intl.DateTimeFormat('sv-SE', { timeZone: TZ }).format(start)
    const parts = Object.fromEntries(
      new Intl.DateTimeFormat('en-GB', { timeZone: TZ, hour: '2-digit', minute: '2-digit', hour12: false })
        .formatToParts(start).map(p => [p.type, p.value]),
    )
    const hour = Number(parts.hour) % 24
    const minute = Number(parts.minute)
    time = `${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}`
    minutes = hour * 60 + minute
  }

  const name = summary.length > MAX_SUMMARY_LENGTH ? `${summary.slice(0, MAX_SUMMARY_LENGTH - 1)}…` : summary
  const title = `${label ? `${label}: ` : ''}${name}${time ? ` (${time})` : ''}`
  return { title, dueDate, minutes, timeOfDay: timeOfDayFor(minutes) }
}

export async function syncDutyCalendar() {
  const url = process.env.DUTY_ICAL_URL
  if (!url) return
  if (!url.startsWith('https://')) {
    console.error('Dienstplan: DUTY_ICAL_URL muss mit https:// beginnen')
    return
  }
  const options = {
    filter: (process.env.DUTY_ICAL_FILTER || '').trim(),
    label: (process.env.DUTY_ICAL_LABEL || '').trim(),
  }

  let events
  try {
    events = await fetchIcalWithRetry(url, { label: 'Dienstplan' })
  } catch (err) {
    // Der Link enthält den geheimen Schlüssel - nie ins Log schreiben.
    console.error('Dienstplan: Sync fehlgeschlagen:', String(err.message).replaceAll(url, '<URL>'))
    return
  }

  const today = todayBerlin()
  const horizon = addDaysToDateString(today, BANK_LEAD_DAYS)
  const allEvents = Object.values(events).filter(e => e?.type === 'VEVENT')

  const wanted = new Map() // "titel|datum" -> Dienst
  let recurring = 0
  for (const event of allEvents) {
    if (event.rrule) recurring++
    const duty = dutyFromEvent(event, options)
    if (!duty || duty.dueDate < today || duty.dueDate > horizon) continue
    wanted.set(`${duty.title}|${duty.dueDate}`, duty)
  }
  if (recurring > 0) {
    console.warn(`Dienstplan: ${recurring} Serientermin(e) im Abo - nur der erste Termin einer Serie wird berücksichtigt. Das Abo sollte Einzeltermine liefern.`)
  }

  const existing = await prisma.task.findMany({ where: { autoSource: DUTY_SOURCE, dueDate: { gte: today } } })
  const existingByKey = new Map(existing.map(t => [`${t.title}|${t.dueDate}`, t]))

  let created = 0
  for (const [key, duty] of wanted) {
    if (existingByKey.has(key)) {
      existingByKey.delete(key)
      continue
    }
    await prisma.task.create({
      data: {
        title: duty.title,
        type: 'once',
        priority: 'normal',
        dueDate: duty.dueDate,
        isAutoGenerated: true,
        autoSource: DUTY_SOURCE,
        isActive: true,
        sortOrder: duty.minutes ?? 0,
        timeOfDay: duty.timeOfDay,
      },
    })
    created++
  }

  // Übrig: vorgemerkte Dienste, die nicht mehr im Abo stehen (getauscht oder
  // gestrichen). Nur entfernen, wenn das Abo überhaupt Termine geliefert hat -
  // eine leere Antwort (Störung beim Anbieter) soll nichts wegräumen - und nie,
  // wenn der Dienst schon abgehakt wurde.
  let removed = 0
  const stale = [...existingByKey.values()]
  if (stale.length > 0 && allEvents.length > 0) {
    const done = new Set((await prisma.taskCompletion.findMany({
      where: { taskId: { in: stale.map(t => t.id) } },
      select: { taskId: true },
    })).map(c => c.taskId))
    const toRemove = stale.filter(t => !done.has(t.id)).map(t => t.id)
    if (toRemove.length > 0) {
      await prisma.task.deleteMany({ where: { id: { in: toRemove } } })
      removed = toRemove.length
    }
  }

  if (created > 0 || removed > 0) {
    console.log(`Dienstplan: ${created} Aufgabe(n) angelegt, ${removed} entfernt`)
    broadcastTasksUpdated()
  }
}
